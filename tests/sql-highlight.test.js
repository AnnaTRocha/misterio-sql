import test from 'node:test';
import assert from 'node:assert/strict';
import { bindSqlHighlight, highlightSql } from '../js/sql-highlight.js';

test('realça palavras SQL e preserva conteúdo escapado com strings intactas', () => {
  const html = highlightSql("SELECT COUNT(*) FROM usuarios WHERE nome = '<script>' -- pista");
  assert.ok(html.includes('<span class="sql-token-keyword">SELECT</span>'));
  assert.ok(html.includes('<span class="sql-token-function">COUNT</span>'));
  assert.ok(html.includes('<span class="sql-token-string">&#039;&lt;script&gt;&#039;</span>'));
  assert.ok(html.includes('<span class="sql-token-comment">-- pista</span>'));
  assert.ok(!html.includes('<script>'));
});

test('realça sintaxe PostgreSQL ensinada no DDL', () => {
  const html = highlightSql('id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
  for (const keyword of ['GENERATED', 'BY', 'DEFAULT', 'AS', 'IDENTITY', 'PRIMARY', 'KEY']) {
    assert.ok(html.includes(`class="sql-token-keyword">${keyword}</span>`));
  }
  assert.ok(html.includes('class="sql-token-type">INTEGER</span>'));
});

test('espelha edição e acompanha a rolagem do editor', () => {
  const handlers = {};
  const editor = {
    value: 'SELECT * FROM usuarios;',
    scrollTop: 30,
    scrollLeft: 12,
    addEventListener: (name, handler) => { handlers[name] = handler; }
  };
  const code = { innerHTML: '', style: {} };

  const refresh = bindSqlHighlight(editor, code);
  assert.ok(code.innerHTML.includes('sql-token-keyword'));
  assert.equal(code.style.transform, 'translate(-12px, -30px)');

  editor.value = 'SELECT nome FROM pessoas;';
  editor.scrollTop = 60;
  handlers.input();
  assert.ok(code.innerHTML.includes('nome'));
  assert.equal(code.style.transform, 'translate(-12px, -60px)');

  editor.scrollLeft = 24;
  handlers.scroll();
  assert.equal(code.style.transform, 'translate(-24px, -60px)');
  assert.equal(typeof refresh, 'function');
});
